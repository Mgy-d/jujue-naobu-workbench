import MarkdownIt from 'markdown-it'
import {readResearchProgress} from '@/utils/researchProgress'

// Agent text is untrusted. Raw HTML stays escaped and unsafe link schemes stay disabled.
const markdown = new MarkdownIt({html:false,breaks:true,linkify:false})

/** Hide tagged reasoning, including incomplete streaming blocks, outside code fences. */
export function researchVisibleText(text:string):string {
  let hidden=false
  let fence=''
  const output:string[]=[]
  for(const line of text.split('\n')){
    const marker=line.match(/^ {0,3}(`{3,}|~{3,})/)
    if(fence){
      output.push(line)
      if(marker && marker[1]![0]===fence[0] && marker[1]!.length>=fence.length && /^ {0,3}(`{3,}|~{3,})\s*$/.test(line))fence=''
      continue
    }
    if(!hidden && marker){fence=marker[1]!;output.push(line);continue}
    const tags=/<(?:thinking|think)(?:\s[^>]*>|>|(?=[A-Z0-9\u4e00-\u9fff]))|<\/(?:thinking|think)\s*>/g
    let visible='',cursor=0
    for(const match of line.matchAll(tags)){
      if(!hidden)visible+=line.slice(cursor,match.index)
      hidden=!match[0].startsWith('</')
      cursor=match.index!+match[0].length
    }
    if(!hidden)visible+=line.slice(cursor)
    // A partial opening tag can arrive at the end of a streamed text fragment.
    visible=visible.replace(/<(?:t|th|thi|thin|think|thinki|thinkin|thinking)$/i,'')
    // Hide transport identifiers in prose, while keeping paths and code examples intact.
    visible=visible.replace(/(?:【项目ID】|项目\s*(?:(?:ID|编号)\s*[:：]?)?)\s*(\*\*|__|\*|_|`|)sz-[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\1/gi,'项目')
    if(visible.trim())output.push(visible)
    else if(!hidden)output.push('')
  }
  return output.join('\n')
}

/** Remove only the anchored envelope generated by the research message sender. */
export function researchUserDisplayText(text:string):string {
  const generatedEnvelope=/^(?:【项目ID】[ \t]*sz-[A-Za-z0-9-]+\r?\n|研究主题：[^\r\n]*\r?\n\r?\n我的问题或补充说明：\r?\n)/.test(text)
  let visible=text.replace(/^【项目ID】[ \t]*sz-[A-Za-z0-9-]+\r?\n/,'')
  visible=visible.replace(/^研究主题：[^\r\n]*\r?\n\r?\n我的问题或补充说明：\r?\n/,'')
  if(generatedEnvelope){
    const marker=/\r?\n\r?\n本会话已上传材料引用（需读取核对）：\r?\n/.exec(visible)
    if(marker){
      const names=visible.slice(marker.index+marker[0].length).split(/\r?\n\r?\n/,1)[0]!.split(/\r?\n/)
        .flatMap(line=>{const match=/^(.+?)\s+@?uploads\/[^\s]+\s*$/.exec(line);return match?[match[1]!.trim()]:[]})
      if(names.length)visible=visible.slice(0,marker.index).trimEnd()+'\n\n已附加文件：'+[...new Set(names)].join('、')
    }
    visible=visible.replace(/\r?\n\r?\n[（(]以下附件体积超过内联上限[\s\S]*[）)]\s*$/u,'')
  }
  return visible
}

export function renderResearchMessage(text:string, role:'user'|'assistant'):string {
  if(role==='assistant'){
    if(readResearchProgress(text))text=text.slice(0,text.lastIndexOf('[进度]')).trimEnd()
    text=researchVisibleText(text)
    if(/^Let your light shine bright\.[\s]*$/i.test(text.trim()))return ''
  }
  else text=researchUserDisplayText(text)
  if(!text.replace(/[\s\u200B\uFEFF]/g,''))return ''
  if(role==='assistant')return markdown.render(text)
  return text.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/\r?\n/g,'<br />')
}
