// Agent text is untrusted. Raw HTML stays escaped and unsafe link schemes stay disabled.
const markdown = new MarkdownIt({html:false,breaks:true,linkify:false})
import {readableResearchText as readablePhases} from './researchDisplayText'
export {readablePhases}
function renderMarkdown(text:string):string {return markdown.render(readablePhases(text)).replace(/<li>\s*(?:<p>\s*<\/p>\s*)?<\/li>/g,'').replace(/<(ol|ul)(?: [^>]*)?>\s*<\/\1>/g,'')}

/** Hide tagged reasoning, including incomplete streaming blocks, outside code fences. */
export function researchVisibleText(text:string):string {
  let hidden=false
  let fence=''
  const output:string[]=[]
  for(const line of text.split('\n')){
    const marker=line.match(/^ {0,3}(`{3,}|~{3,})/)
    if(fence){
      output.push(line)
      if(marker && marker[1]![0]===fence[0] && marker[1]!.length>=fence.length && /^ {0,3}(`{3,}|~{3,})\s*$/.test(line))fence=''
      continue
    }
    if(!hidden && marker){fence=marker[1]!;output.push(line);continue}
    const tags=/\\?<(?:previous_reasoning|thinking|think)(?:\s[^>]*>|>|(?=[A-Z0-9\u4e00-\u9fff]))|\\?<\/(?:previous_reasoning|thinking|think)\s*>/g
    let visible='',cursor=0
    for(const match of line.matchAll(tags)){
      if(!hidden)visible+=line.slice(cursor,match.index)
      hidden=!/\\?<\//.test(match[0])
      cursor=match.index!+match[0].length
    }
    if(!hidden)visible+=line.slice(cursor)
    // A partial opening tag can arrive at the end of a streamed text fragment.
    visible=visible.replace(/\\?<(?:t|th|thi|thin|think|thinki|thinkin|thinking|previous(?:_reasoning)?)$/i,'')
    visible=visible.replace(/\\?<\/?care\s*>/gi,'')
    // Hide transport identifiers in prose, while keeping paths and code examples intact.
    visible=visible.replace(/(?:【项目ID】|项目\s*(?:(?:ID|编号)\s*[:：]?)?)\s*(\*\*|__|\*|_|`|)sz-[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\1/gi,'项目')
    if(visible.trim())output.push(visible)
    else if(!hidden)output.push('')
  }
  return stripResearchToolMarkup(output.join('\n'))
}

/** Known machine-directed reminders are excluded from presentation, not from stored evidence. */
export function isResearchAutomaticReminder(text:string):boolean {
 // Match the observed transport-only envelope, never arbitrary tagged user prose.
 const emptyReplyReminder=/^\s*(?:<system-reminder>\s*Your previous reply had empty content\s*-\s*the full answer was written to the reasoning channel only\.\s*Reply again and write the final answer into the content channel\.\s*<\/system-reminder>\s*)+$/i
 if(emptyReplyReminder.test(text))return true
 return /^\s*(?:\[declarative-ending\]\s*)?\[停滞自检\]\s*平台检测到/u.test(text)
  && /平台自动提醒/u.test(text) && /\[平台台账\]/u.test(text)
}
/** Only platform-generated leading envelopes qualify, never quoted user prose. */
export function isResearchPlatformNotice(text:string):boolean {
  return isResearchAutomaticReminder(text)||/^\s*\[异步任务完成通知\]\s*收到以下来自后台子智能体的完成事件[，,]/u.test(text)
}
function platformNoticeHtml(text:string):string {
  if(/(?:^|\n)\s*\[run-failure-retry\]/.test(text))return ''
  const ledger=/^\[平台台账\]\s*$/mu.exec(text)
  if(!ledger)return /失败|错误|超时|冲突|未通过/u.test(text)?renderMarkdown('**平台状态需核对**\n\n'+text):''
  const body=text.slice(ledger.index+ledger[0].length).split('\n')
    .filter(line=>!/^\s*(?:不要重新推导计划[；;]|先完成「下一步」|台账里的结果直接采信)/u.test(line))
    .join('\n').replace(/^\s*下一步[：:]\s*/u,'').trim()
  if(!body)return ''
  const warnings=text.slice(0,ledger.index).split(/\n\s*\n/).filter(part=>/失败|错误|超时|冲突|未通过/u.test(part))
  return renderMarkdown('**待处理事项**\n\n'+userFacingProse(body)+(warnings.length?'\n\n'+warnings.map(userFacingProse).join('\n\n'):''))
}

/** Remove only the anchored envelope generated by the research message sender. */
export function researchUserDisplayText(text:string):string {
  const generatedEnvelope=/^(?:【项目ID】[ \t]*sz-[A-Za-z0-9-]+\r?\n|研究主题：[^\r\n]*\r?\n\r?\n我的问题或补充说明：\r?\n)/.test(text)
  let visible=text.replace(/^【项目ID】[ \t]*sz-[A-Za-z0-9-]+\r?\n/,'')
  visible=visible.replace(/^研究主题：[^\r\n]*\r?\n\r?\n我的问题或补充说明：\r?\n/,'')
  if(generatedEnvelope){
    const marker=/\r?\n\r?\n本会话已上传材料引用（需读取核对）：\r?\n/.exec(visible)
    if(marker){
      const names=visible.slice(marker.index+marker[0].length).split(/\r?\n\r?\n/,1)[0]!.split(/\r?\n/)
        .flatMap(line=>{const match=/^(.+?)\s+@?uploads\/[^\s]+\s*$/.exec(line);return match?[match[1]!.trim()]:[]})
      if(names.length)visible=visible.slice(0,marker.index).trimEnd()+'\n\n已附加文件：'+[...new Set(names)].join('、')
    }
    visible=visible.replace(/\r?\n\r?\n[（(]以下附件体积超过内联上限[\s\S]*[）)]\s*$/u,'')
  }
  return visible
}

/** Split prose only outside inline code. Lists, tables and fenced examples are left intact. */
function proseSentences(text:string):string[] {
  const parts:string[]=[];let start=0,code=''
  for(let i=0;i<text.length;i++){
    if(text[i]==='`'){
      let end=i+1;while(text[end]==='`')end++
      const ticks=text.slice(i,end);code=code===ticks?'':code||ticks;i=end-1;continue
    }
    if(!code && /[。；！？]/u.test(text[i]!)){parts.push(text.slice(start,i+1));start=i+1}
  }
  if(start<text.length)parts.push(text.slice(start))
  return parts.filter(part=>part.trim())
}
function userFacingProse(text:string):string {
  const plain=(part:string)=>part
    .replace(/\bS1\s*[/／]\s*S3\s*[/／]\s*S12\b/g,'标题页、目录和参考文献')
    .replace(/\bS(1|3|12)\b(?![\w./\\-]|\s*(?:标题页|目录|参考文献))/g,(_match,n:string)=>({'1':'标题页','3':'目录','12':'参考文献'}[n]!))
    .replace(/(?:闸门|阀门)/g,'审核确认')
    .replace(/draftedBy\s*=\s*AI/g,'由 AI 起草')
    .replace(/status\s*=\s*drafted/g,'状态为初稿')
    .replace(/purpose\s*=\s*正文起草/g,'用途为正文起草')
    .replace(/<!--\s*aiDrafted\s*-->/gi,'AI 起草标记')
    .replace(/(?<![\w/.\\-])validate_report(?![\w/.\\-])/g,'报告格式校验')
    .replace(/ok\s*=\s*true/g,'格式检查通过').replace(/ok\s*=\s*false/g,'格式检查未通过')
    .replace(/(?<![\w/.\\-])aiDrafted(?![\w/.\\-])/g,'AI 起草')
    .replace(/(?<![\w/.\\-])drafted(?![\w/.\\-])/g,'初稿')
    .replace(/(?<![\w/.\\-])pending(?![\w/.\\-])/g,'待补充')
  // Preserve links and code/path examples verbatim. Translate only exact known status spans.
  const protectedSpan=/(`+)([^`\n]*?)\1|\[[^\]\n]*\]\([^\n)]*\)|https?:\/\/[^\s]+/g
  let result='',cursor=0
  for(const match of text.matchAll(protectedSpan)){
    result+=plain(text.slice(cursor,match.index))
    const value=match[2]
    if(value!==undefined && /^(?:draftedBy\s*=\s*AI|status\s*=\s*drafted|purpose\s*=\s*正文起草|<!--\s*aiDrafted\s*-->|validate_report|ok\s*=\s*(?:true|false)|aiDrafted|drafted|pending)$/.test(value))result+=plain(value)
    else if(value==='##' && /^\s*前缀/.test(text.slice(match.index!+match[0].length)))result+='二级标题标记'
    else result+=match[0]
    cursor=match.index!+match[0].length
  }
  return (result+plain(text.slice(cursor)))
    .replace(/报告格式校验\s*(?:现在)?返回\s*格式检查(未)?通过\s*[:：]?/g,(_all,failed:string|undefined)=>'报告格式检查'+(failed?'未':'')+'通过：')
    .replace(/\bS\d+\s*(标题页|目录|参考文献)/g,'$1')
}
function internalOnlySentence(text:string):boolean {
  // Fold only recognizable implementation instructions/counters, not mixed risk or decision text.
  if(/风险|失败|错误|超时|冲突|缺失|丢失|未通过|不通过|不能|不得|禁止|等待|审核|批准|闸门|确认|尚未|未执行|待补充|请|(?:由|为|是)\s*AI\s*起草|AI\s*生成/u.test(text))return false
  return /^\s*按\s*Never\s*\d+[^。；]*接口约定/u.test(text)
    || /^\s*(?:骨架加\s*`?<!--\s*aiDrafted|AI\s*记录写\s*`?purpose=)/u.test(text)
    || /^\s*`?(?:pendingBlocksWithText|conclusionHits)\s*=\s*\d+`?(?:\s*[、,，]\s*`?(?:pendingBlocksWithText|conclusionHits)\s*=\s*\d+`?)*[。；]?\s*$/u.test(text)
    || /^\s*再?刷新\s*`?manifest(?:\.json)?`?\s*并(?:申报|记录)[。；]?\s*$/u.test(text)
}
/** Deterministic display adaptation only. It never modifies stored replies or authorizes a phase. */
export function renderUserFacingAssistant(source:string):string {
  const lines=source.split('\n');const tokens=markdown.parse(source,{})
  let changed=false
  const paragraphs=tokens.filter(token=>token.type==='paragraph_open' && token.level===0 && token.map)
  for(const token of paragraphs.reverse()){
    const [start,end]=token.map!
    const original=lines.slice(start,end).join('\n')
    const hasEmphasis=markdown.parseInline(original,{})[0]?.children?.some(token=>['em_open','strong_open','s_open'].includes(token.type)) ?? false
    const routine=/^(?:本轮|两个生成脚本已就位|清单与 README 已同步)/.test(original.trim())&&/脚本|清单|指纹|字节|接口|申报|README|正则|校验器/.test(original)&&!/风险|失败|错误|警告|不一致|缺失|无法|未通过|审核|确认|AI|匿名|禁止|不得/.test(original)
    if(routine){changed=true;lines.splice(start,end-start,'');continue}
    const sentences=hasEmphasis?[original]:proseSentences(original)
    const publicParts=sentences.filter(sentence=>hasEmphasis || !internalOnlySentence(sentence)).map(userFacingProse)
    const replacement=publicParts.join('')
    if(replacement!==original){changed=true;lines.splice(start,end-start,replacement)}
  }
  const visible=lines.join('\n').trim()
  if(!changed)return renderMarkdown(source)
  return visible?renderMarkdown(visible):''
}

export function renderResearchMessage(text:string, role:'user'|'assistant'):string {
  if(isResearchAutomaticReminder(text))return ''
  if(isResearchPlatformNotice(text))return platformNoticeHtml(researchVisibleText(text))
  if(role==='assistant'){
    if(readResearchProgress(text))text=text.slice(0,text.lastIndexOf('[进度]')).trimEnd()
    text=researchVisibleText(text)
    if(/^Let your light shine bright\.[\s]*$/i.test(text.trim()))return ''
  }
  else text=researchUserDisplayText(text)
  if(!text.replace(/[\s\u200B\uFEFF]/g,''))return ''
  if(role==='assistant'){
    const timeout=researchResponseTimeout(text)
    if(timeout){
      const escape=(value:string)=>value.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')
      const before=text.slice(0,timeout.start).trim(),after=text.slice(timeout.end).trim()
      return (before?renderUserFacingAssistant(before):'')+'<section class="message-timeout" role="alert"><strong>本次处理超时，结果待核对</strong><p>模型服务在 '+timeout.seconds+' 秒内未完成回复。已执行的修改与最终结果需要核对；这不代表审核通过，也不代表只能等待补充材料。</p><p>请先核对原会话与已保存文件，避免重复修改或重复提交。</p><details><summary>错误详情</summary><pre>'+escape(timeout.raw)+'</pre></details></section>'+(after?renderUserFacingAssistant(after):'')
    }
    return renderUserFacingAssistant(text)
  }
  return readablePhases(text).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/\r?\n/g,'<br />')
}
